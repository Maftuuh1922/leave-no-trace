"""Render a diff (and optionally a plan) as a terminal or markdown receipt."""
from __future__ import annotations

import os
import sys
import time

from .diff import SEVERITY_ORDER, actionable
from .util import human_bytes

GROUP_WORDS = {
    "AGENT-CONFIG": ("agent config/hook change", "agent config/hook changes"),
    "PERSISTENCE": ("scheduled job/service", "scheduled jobs/services"),
    "RUNNING": ("running process/port/container", "running processes/ports/containers"),
    "ENV": ("global environment change", "global environment changes"),
    "LITTER": ("leftover file", "leftover files"),
    "OTHER": ("other change", "other changes"),
}


def _ts(epoch):
    if not epoch:
        return "?"
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(epoch))


def evidence_str(f) -> str:
    ev = f["evidence"]["after"] or f["evidence"]["before"]
    parts = []
    if "sha256" in ev:
        before = f["evidence"]["before"].get("sha256")
        if before and f["change"] == "modified":
            parts.append("sha256 %s→%s" % (before[:10], ev["sha256"][:10]))
        else:
            parts.append("sha256 %s" % ev["sha256"][:12])
    if "pid" in ev:
        parts.append("pid %s" % ev["pid"])
    if "start" in ev:
        parts.append("started %s" % _ts(ev["start"]))
    if ev.get("cwd"):
        parts.append("cwd %s" % ev["cwd"].replace(os.path.expanduser("~"), "~", 1))
    if ev.get("children"):
        parts.append("children %s" % ",".join(str(c) for c in ev["children"]))
    if "procs" in ev:
        parts.append("; ".join("pid %s started %s" % (p.get("pid"), _ts(p.get("start"))) for p in ev["procs"]))
    if "size" in ev and isinstance(ev["size"], int):
        parts.append(human_bytes(ev["size"]))
    if "mode" in ev and f["category"] in ("dotfile", "agentconfig", "repo.untracked", "unit"):
        parts.append("mode %s" % ev["mode"])
    if "version" in ev:
        parts.append("v%s" % ev["version"])
    if ev.get("secret"):
        parts.append("hash only (may hold credentials)")
    return ", ".join(parts)


def headline(diff, fail_on="low") -> str:
    items = actionable(diff, fail_on)
    if not items:
        return "Clean: nothing changed outside the requested work."
    counts = {}
    for f in items:
        counts[f["group"]] = counts.get(f["group"], 0) + 1
    bits = []
    for g in ("AGENT-CONFIG", "PERSISTENCE", "RUNNING", "ENV", "LITTER", "OTHER"):
        if g in counts:
            n = counts[g]
            bits.append("%d %s" % (n, GROUP_WORDS[g][0 if n == 1 else 1]))
    return "This session left %d thing%s outside the requested work: %s." % (
        len(items), "" if len(items) == 1 else "s", ", ".join(bits))


def render(diff, fmt="text", plan=None, fail_on="low", show_all=False, color=None) -> str:
    if color is None:
        color = fmt == "text" and sys.stdout.isatty() and not os.environ.get("NO_COLOR")
    items = actionable(diff, fail_on)
    shown = diff["findings"] if show_all else items
    scoped = [f for f in diff["findings"] if f["in_scope"]]
    ignored = [f for f in diff["findings"] if f["ignored_by"]]
    plan_by_finding = {}
    for a in plan or []:
        plan_by_finding.setdefault(a["finding"], []).append(a)
    title = "Leave No Trace receipt"
    window = "%s → %s" % (_ts(diff["before_taken_at"]), _ts(diff["after_taken_at"]))
    lines = []
    if fmt == "md":
        lines.append("## %s" % title)
        lines.append("")
        lines.append("**%s**" % headline(diff, fail_on))
        lines.append("")
        lines.append("Repo `%s` · session %s · %d in-scope change(s) · %d ignored" % (
            diff["repo_root"].replace(os.path.expanduser("~"), "~", 1), window, len(scoped), len(ignored)))
        lines.append("")
        if shown:
            lines.append("| # | Kind | Severity | What | Evidence | Suggested revert |")
            lines.append("|---|---|---|---|---|---|")
            for i, f in enumerate(shown, 1):
                rv = "; ".join("`%s`" % a["description"] if a["kind"] in ("command", "git") else a["description"]
                               for a in plan_by_finding.get(f["id"], [])) or "–"
                lines.append("| %d | %s | %s | %s | %s | %s |" % (
                    i, f["group"], f["severity"], _md(f["title"]), _md(evidence_str(f)), _md(rv)))
            lines.append("")
        for n in diff.get("notes", []):
            lines.append("> %s" % n)
        lines.append("")
        lines.append("_Generated by [leave-no-trace](https://github.com/Maftuuh1922/leave-no-trace). Hashes only; file contents are never printed._")
        return "\n".join(lines) + "\n"
    bold = (lambda s: "\033[1m%s\033[0m" % s) if color else (lambda s: s)
    sev_col = {"high": "\033[31m", "medium": "\033[33m", "low": "\033[36m", "info": "\033[2m"}
    lines.append(bold("━━ %s ━━" % title))
    lines.append("repo: %s   session: %s" % (diff["repo_root"], window))
    lines.append(bold(headline(diff, fail_on)))
    lines.append("")
    for i, f in enumerate(shown, 1):
        sev = f["severity"].upper()
        if color:
            sev = sev_col.get(f["severity"], "") + sev + "\033[0m"
        tag = " (ignored: %s)" % f["ignored_by"] if f["ignored_by"] else (" (in scope)" if f["in_scope"] else "")
        lines.append("%2d. [%s] %s %s%s" % (i, f["group"], sev, f["title"], tag))
        ev = evidence_str(f)
        if ev:
            lines.append("      evidence: %s" % ev)
        for a in plan_by_finding.get(f["id"], []):
            lines.append("      revert:   %s" % a["description"])
    if shown:
        lines.append("")
    lines.append("%d in-scope change(s), %d ignored finding(s)." % (len(scoped), len(ignored)))
    for n in diff.get("notes", []):
        lines.append("note: %s" % n)
    return "\n".join(lines) + "\n"


def _md(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def severity_ok(level: str) -> bool:
    return level in SEVERITY_ORDER
